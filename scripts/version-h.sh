#!/bin/sh
# Generates version.h from lib/backburn/version.rb, the only version source.
set -e
version=$(sed -n 's/^ *VERSION *= *"\([^"]*\)".*/\1/p' "$1")
test -n "$version" || { echo "version-h.sh: no VERSION in $1" >&2; exit 1; }
echo "/* Generated by scripts/version-h.sh from $1. Do not edit. */"
echo "#define BACKBURN_VERSION \"$version\""
