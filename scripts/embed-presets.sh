#!/bin/sh
# Compiles presets/*.roots into presets.h so a single backburn binary works anywhere.
set -e
echo "/* Generated by scripts/embed-presets.sh from the presets directory. Do not edit. */"
echo "static const struct { const char *name; const char *text; } PRESETS[] = {"
for f in "$@"; do
  name=$(basename "$f" .roots)
  printf '    {"%s",\n' "$name"
  awk '{ gsub(/\\/, "\\\\"); gsub(/"/, "\\\""); printf "     \"%s\\n\"\n", $0 }' "$f"
  printf '    },\n'
done
echo "    {0, 0}"
echo "};"
